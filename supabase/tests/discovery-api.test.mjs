import assert from 'node:assert/strict';
import {readdir, readFile} from 'node:fs/promises';
import {test} from 'node:test';
import {PGlite} from '@electric-sql/pglite';
import {createChatHandler} from '../../apps/api/chat.mjs';

const [alex,maya,sam,gym,unapproved] = [1,2,3,4,5].map(n=>`00000000-0000-4000-8000-00000000000${n}`);

test('verified identity owns onboarding and reciprocal discovery omits hidden information',async t=>{
  const db=await PGlite.create();
  t.after(()=>db.close());
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; create table auth.users(id uuid primary key);`);
  const root=new URL('../migrations/',import.meta.url);
  for(const file of (await readdir(root)).filter(name=>name.endsWith('.sql')).sort()) await db.exec(await readFile(new URL(file,root),'utf8'));
  await db.query('insert into auth.users values ($1),($2),($3)',[alex,maya,sam]);
  await db.exec("insert into spotme_private.cities(province,municipality_code,name) values ('ON','fixture','Kitchener')");
  await db.query(`insert into spotme_private.gyms(id,city_id,display_name,street_address,listing_status)
    values ($1,1,'Sample Club','Example Road','approved'),($2,1,'Hidden Gym','Example Road','pending')`,[gym,unapproved]);
  await db.exec('set role authenticated');
  await assert.rejects(db.query('select spotme_private.read_profile($1)',[alex]),{code:'42501'});
  await db.exec('reset role; set role spotme_chat_api');
  const app=createChatHandler({db,verify:async token=>({'alex.test.token':alex,'maya.test.token':maya,'sam.test.token':sam})[token]});
  const call=(actor,path,method='GET',data)=>app(new Request(`https://example.test/v1/${path}`,{method,
    headers:{authorization:`Bearer ${actor}.test.token`,'content-type':'application/json'},body:data===undefined?undefined:JSON.stringify(data)}));
  const profile=(name,gender,seeking)=>({name,gender,seeking,date_of_birth:'1994-01-01',city_id:'1',bio:'Training together',intent:'Relationship',split:'Full body',days:[1,3],days_audience:'private',minimum_age:18,maximum_age:99,gyms:[{id:gym,audience:'private'}],paused:false});
  const save=(actor,p)=>call(actor,'me/profile','PUT',p);
  const cards=async actor=>(await (await call(actor,'discovery')).json()).cards;
  const like=(actor,id)=>call(actor,'swipes','POST',{peer_id:id,decision:'like'});
  const city=(await (await call('alex','cities')).json()).cities[0];
  assert.equal(city.id,'1');
  assert.deepEqual((await (await call('alex','gyms?city=1')).json()).gyms.map(g=>g.id),[gym]);
  assert.deepEqual((await (await call('alex','me/profile')).json()).profile,null);
  assert.equal((await save('alex',{...profile('Alex','man',['woman']),date_of_birth:'2020-01-01'})).status,422);
  assert.equal((await save('alex',{...profile('Alex','man',['woman']),user_id:maya})).status,422);
  const result=await save('alex',profile('Alex','man',['woman']));
  assert.equal(result.status,200);
  assert.equal((await result.json()).profile.status,'onboarding');
  assert.equal((await save('maya',profile('Maya','woman',['man']))).status,200);
  assert.equal((await save('sam',profile('Sam','woman',['woman']))).status,200);
  assert.equal((await save('maya',{...profile('Maya','woman',['man']),gyms:[{id:unapproved,audience:'discovery'}]})).status,422);
  assert.equal((await save('maya',{...profile('Maya','woman',['man']),date_of_birth:'1990-01-01'})).status,422);
  assert.deepEqual(await cards('alex'),[]);
  assert.equal((await like('alex',maya)).status,404);
  const suggestion={city_id:'1',name:'Missing Gym',address:'Demo address'};
  const first=await (await call('alex','gym-submissions','POST',suggestion)).json();
  assert.equal(first.status,'pending');
  assert.deepEqual(await (await call('alex','gym-submissions','POST',suggestion)).json(),first);
  assert.deepEqual((await (await call('alex','gyms?city=1&q=Missing')).json()).gyms,[]);
  await db.exec("reset role; update spotme_private.profiles set status='active',discovery_approved_at=now(); set role spotme_chat_api");
  assert.equal((await like('alex',sam)).status,404);
  const [card]=await cards('alex');
  assert.equal(card.id,maya);
  assert.deepEqual(card.gyms,[]);
  assert.deepEqual(card.days,[]);
  assert.equal(card.date_of_birth,undefined);
  assert.equal(card.seeking,undefined);
  const update=await save('maya',{...profile('Maya','woman',['man']),days_audience:'discovery',gyms:[{id:gym,audience:'discovery'}]});
  assert.equal(update.status,200);
  assert.deepEqual((await cards('alex'))[0].days,[1,3]);
  assert.deepEqual((await cards('alex'))[0].gyms,['Sample Club']);
  assert.deepEqual(await (await like('alex',maya)).json(),{matched:false});
  assert.deepEqual(await cards('alex'),[]);
  assert.deepEqual(await (await like('maya',alex)).json(),{matched:true});
  assert.equal((await (await call('alex','matches')).json()).matches[0].peer_id,maya);
  const report={peer_id:maya,client_report_id:gym,reason:'harassment',details:'Test report'};
  const reported=await call('alex','reports','POST',report);
  assert.equal(reported.status,201);
  assert.deepEqual(await (await call('alex','reports','POST',report)).json(),await reported.json());
  assert.equal((await call('sam','reports','POST',report)).status,404);
  await assert.rejects(db.query('select * from spotme_private.member_reports'),{code:'42501'});
  await assert.rejects(db.query('select spotme_private.resolve_gym_suggestion($1,$2)',[first.id,gym]),{code:'42501'});
  await db.exec('reset role; set role service_role');
  assert.equal((await db.query('select spotme_private.resolve_gym_suggestion($1,$2) as resolved',[first.id,gym])).rows[0].resolved,true);
  assert.equal((await db.query('select spotme_private.resolve_gym_suggestion($1,$2) as resolved',[first.id,gym])).rows[0].resolved,false);
  await db.exec('reset role; set role spotme_chat_api');
  assert.equal((await call('alex',`blocks/${maya}`,'POST')).status,204);
  assert.equal((await like('maya',alex)).status,404);
});
